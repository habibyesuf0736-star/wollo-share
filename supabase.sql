create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  role text not null default 'student' check (role in ('student', 'admin')),
  access_granted boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists access_granted boolean not null default false;

create table if not exists public.video_progress (
  user_id uuid not null references public.profiles (id) on delete cascade,
  video_id text not null,
  completed_at timestamptz not null default now(),
  primary key (user_id, video_id)
);

create table if not exists public.user_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  event_type text not null check (event_type in ('sign_in', 'resource_open', 'video_completed', 'video_uncompleted')),
  resource_id text,
  created_at timestamptz not null default now()
);

create index if not exists user_activity_created_at_idx on public.user_activity (created_at desc);
create index if not exists user_activity_user_id_created_at_idx on public.user_activity (user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.video_progress enable row level security;
alter table public.user_activity enable row level security;

grant select on public.profiles to authenticated;
grant update (access_granted) on public.profiles to authenticated;
grant select, insert, delete on public.video_progress to authenticated;
grant select, insert on public.user_activity to authenticated;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create or replace function public.has_app_access()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and access_granted = true
  );
$$;

revoke all on function public.has_app_access() from public, anon;
grant execute on function public.has_app_access() to authenticated;

drop policy if exists "Profiles visible to owner and admins" on public.profiles;
create policy "Profiles visible to owner and admins"
on public.profiles
for select
to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Admins manage learner access" on public.profiles;
create policy "Admins manage learner access"
on public.profiles
for update
to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

drop policy if exists "Progress visible to owner and admins" on public.video_progress;
create policy "Progress visible to owner and admins"
on public.video_progress
for select
to authenticated
using ((select public.is_admin()) or (user_id = (select auth.uid()) and (select public.has_app_access())));

drop policy if exists "Learners add their own progress" on public.video_progress;
create policy "Learners add their own progress"
on public.video_progress
for insert
to authenticated
with check (user_id = (select auth.uid()) and ((select public.has_app_access()) or (select public.is_admin())));

drop policy if exists "Learners remove their own progress" on public.video_progress;
create policy "Learners remove their own progress"
on public.video_progress
for delete
to authenticated
using (user_id = (select auth.uid()) and ((select public.has_app_access()) or (select public.is_admin())));

drop policy if exists "Activity visible to owner and admins" on public.user_activity;
create policy "Activity visible to owner and admins"
on public.user_activity
for select
to authenticated
using (user_id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Learners record their own activity" on public.user_activity;
create policy "Learners record their own activity"
on public.user_activity
for insert
to authenticated
with check (
  user_id = (select auth.uid())
  and (
    event_type = 'sign_in'
    or (select public.has_app_access())
    or (select public.is_admin())
  )
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

